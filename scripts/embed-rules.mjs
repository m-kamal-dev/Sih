/**
 * Embeds the YAML rule pack into the engine as a generated TypeScript module,
 * so servers never need to read rules/ from disk (serverless hosts such as
 * Vercel only ship files the bundler traces). The engine test
 * "embedded rule pack matches rules/ on disk" fails if this is out of date.
 *
 * Usage: node scripts/embed-rules.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'rules', 'aph-2024-27');
const out = path.join(root, 'packages', 'engine', 'src', 'rulepack.generated.ts');

const files = readdirSync(dir).filter((f) => f.endsWith('.yaml') || f.endsWith('.yml')).sort();
const entries = files.map((file) => `  { file: ${JSON.stringify(file)}, yaml: ${JSON.stringify(readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n'))} },`);

writeFileSync(out, `// Generated by scripts/embed-rules.mjs from rules/aph-2024-27. Do not edit by hand:
// change the YAML, then run \`node scripts/embed-rules.mjs\`.
export const EMBEDDED_RULE_PACK: readonly { file: string; yaml: string }[] = [
${entries.join('\n')}
];
`);
console.log(`Embedded ${files.length} rule files into packages/engine/src/rulepack.generated.ts`);
